import org.jetbrains.compose.desktop.application.dsl.TargetFormat
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

// The Mac app. It also runs on Windows and Linux for development (.\gradlew.bat :desktop:run), without speech.
plugins {
    alias(libs.plugins.kotlin.jvm)
    alias(libs.plugins.compose.multiplatform)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
}

// Build number, version and update repository: see the root build.gradle.kts.
val commitCount: Int by rootProject.extra
val updateRepo: String by rootProject.extra
val appVersion = rootProject.extra["versionName"] as String

kotlin {
    compilerOptions { jvmTarget.set(JvmTarget.JVM_17) }
}

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

dependencies {
    implementation(project(":shared"))
    implementation(compose.desktop.currentOs)
    implementation(compose.material3)
    implementation("org.jetbrains.compose.material:material-icons-core:${libs.versions.composeMultiplatform.get()}")
    implementation(libs.jetbrains.lifecycle.viewmodel.compose)
    implementation(libs.jetbrains.lifecycle.runtime.compose)
    implementation(libs.kotlinx.coroutines.swing)
    implementation(libs.kotlinx.serialization.json)
    implementation(libs.sqlite.jdbc)
    testImplementation(libs.junit)
}

// The build number and GitHub repository, for Settings > About and the in-app updater.
val generateBuildInfo by tasks.registering {
    val out = layout.buildDirectory.dir("generated/buildInfo")
    val build = commitCount
    val repo = updateRepo
    val version = appVersion
    inputs.property("build", build)
    inputs.property("repo", repo)
    inputs.property("version", version)
    outputs.dir(out)
    doLast {
        val file = out.get().file("com/hanzilock/desktop/BuildInfo.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package com.hanzilock.desktop
            |
            |/** Generated by desktop/build.gradle.kts. */
            |object BuildInfo {
            |    const val BUILD = $build
            |    const val VERSION_NAME = "$version"
            |    const val UPDATE_REPO = "$repo"
            |}
            |""".trimMargin(),
        )
    }
}
kotlin.sourceSets.main { kotlin.srcDir(generateBuildInfo) }

// Bundled with the app: the word sets, sentence corpus and dictionary (repo folder content/), and on the
// Mac the speech helper built from macos/lingo-helper (by the release workflow).
val appResources = layout.buildDirectory.dir("appResources")
val syncAppResources by tasks.registering(Sync::class) {
    from(rootProject.file("content")) { into("common/content") }
    from(rootProject.file("macos/lingo-helper/build")) {
        include("lingo-helper")
        into("macos-arm64")
    }
    into(appResources)
}
tasks.matching { it.name == "prepareAppResources" }.configureEach { dependsOn(syncAppResources) }

compose.desktop {
    application {
        mainClass = "com.hanzilock.desktop.MainKt"
        jvmArgs += listOf("-Xmx1g", "-Dapple.awt.application.appearance=system")
        nativeDistributions {
            targetFormats(TargetFormat.Dmg)
            packageName = "Lingo Lock"
            packageVersion = "${appVersion.substringBeforeLast('.')}.$commitCount"
            description = "Language practice: word sets, stories and a practice gate"
            appResourcesRootDir.set(appResources)
            modules("java.sql", "java.naming", "java.net.http", "jdk.crypto.ec", "jdk.unsupported", "jdk.accessibility")
            macOS {
                bundleID = "com.hanzilock.mac"
                appCategory = "public.app-category.education"
                minimumSystemVersion = "13.0"
                iconFile.set(project.file("icons/LingoLock.icns"))
                infoPlist {
                    extraKeysRawXml = """
                        <key>NSMicrophoneUsageDescription</key>
                        <string>Lingo Lock listens to you pronounce each word.</string>
                        <key>NSSpeechRecognitionUsageDescription</key>
                        <string>Lingo Lock uses speech recognition to check your pronunciation.</string>
                    """.trimIndent()
                }
            }
        }
    }
}
